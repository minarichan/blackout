"""A fixed book used by /portfolio/demo.

The figures are intentional. Arbitrum is a tight ETH-long. Optimism borrows ETH
against USDC, so an ETH rally is the dangerous move. Both go through the same
risk engine as live positions.
"""

from decimal import Decimal

from app.models.position import Position

D = Decimal


def _leg(
    *,
    chain: str,
    protocol: str,
    protocol_name: str,
    market: str,
    market_name: str,
    side: str,
    asset: str,
    asset_address: str,
    amount: str,
    price: str,
    liquidation_threshold: str | None = None,
    collateral_factor: str | None = None,
    collateral: bool = False,
) -> Position:
    qty = D(amount)
    px = D(price)
    threshold = D(liquidation_threshold) if liquidation_threshold is not None else None
    factor = D(collateral_factor) if collateral_factor is not None else None
    return Position(
        id=f"{chain}:{protocol}:{market}:{side}:{asset_address.lower()}",
        user_address="demo",
        chain=chain,
        protocol=protocol,
        protocol_name=protocol_name,
        market=market,
        market_name=market_name,
        account_key=f"{chain}:{protocol}:{market}",
        type=side,  # type: ignore[arg-type]
        asset=asset,
        asset_address=asset_address,
        amount=qty,
        value_usd=qty * px,
        price_usd=px,
        collateral_factor=factor if collateral else None,
        liquidation_threshold=threshold if collateral else None,
        usage_as_collateral=collateral,
        price_source="demo",
        metadata={"book": "demo"},
    )


